#!/usr/bin/env python3
"""Re-pull each Order of 86 wizard's current holder X handle from market.doginaldogs.com.

Writes js/holders.js: window.HOLDERS = {"<dog number>": "<x handle>" | null}.
Only the public X username that the holder linked on the market is kept. Wallet
addresses and inscription IDs are used in memory for the lookup and are never
written, printed or logged.

Lookup chain (all public tRPC GETs, no sign-in):
  search.search {query: "<number>"}            -> the dog's inscription
  wallet.getInscriptionDetails {inscriptionId} -> current owner (in memory only)
  twitter.getProfile {walletAddress}           -> linked X profile, or null

Usage: python3 tools/refresh_holders.py   (run from anywhere; takes ~1 minute)
"""
import datetime, json, pathlib, re, sys, time, urllib.parse, urllib.request

SITE = pathlib.Path(__file__).resolve().parent.parent
API = "https://market.doginaldogs.com/api/trpc/"
HANDLE = re.compile(r"^[A-Za-z0-9_]{1,15}$")


def trpc(proc, inp, tries=3):
    url = API + proc + "?input=" + urllib.parse.quote(json.dumps({"json": inp}))
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (order86-holder-refresh)"})
    for n in range(tries):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.loads(r.read().decode())["result"]["data"]["json"]
        except Exception as e:  # never echo the URL: it can carry an address
            err = type(e).__name__
            time.sleep(1.5 * (n + 1))
    raise RuntimeError("%s failed (%s)" % (proc, err))


def wizard_numbers():
    src = (SITE / "js" / "wizards.js").read_text()
    return [int(n) for n in re.findall(r'"number":\s*(\d+)', src)]


def handle_for(num):
    res = trpc("search.search", {"query": str(num), "limit": 5}).get("results") or []
    hit = next((r for r in res if r.get("dogId") == num), None)
    if not hit:
        return None, "dog not found"
    det = trpc("wallet.getInscriptionDetails", {"inscriptionId": hit["inscriptionId"]}) or {}
    owner = det.get("ownerAddress")
    if not owner:
        return None, "no owner"
    prof = trpc("twitter.getProfile", {"walletAddress": owner})
    owner = None
    user = (prof or {}).get("username") if isinstance(prof, dict) else None
    if user and HANDLE.match(user):
        return user, "linked"
    return None, "not linked"


def main():
    nums = wizard_numbers()
    out, problems = {}, []
    for num in nums:
        try:
            h, why = handle_for(num)
        except Exception as e:
            h, why = None, str(e)
            problems.append((num, why))
        out[str(num)] = h
        print("#%-5d %s" % (num, "@" + h if h else "- (" + why + ")"))
        time.sleep(0.3)
    if len(problems) > len(nums) // 4:
        sys.exit("Too many lookups failed (%d); js/holders.js left unchanged." % len(problems))
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    body = ("/* Order of 86: current holder X handles, from the X account each holder linked on\n"
            " * market.doginaldogs.com. Generated by tools/refresh_holders.py on %s.\n"
            " * Handles only. Never add wallet addresses or inscription IDs here. */\n"
            "window.HOLDERS_UPDATED = %s;\nwindow.HOLDERS = %s;\n") % (
        stamp, json.dumps(stamp), json.dumps(out, indent=0, sort_keys=False))
    (SITE / "js" / "holders.js").write_text(body)
    linked = sum(1 for v in out.values() if v)
    print("\n%d of %d wizards have a linked X holder. Lookup errors: %d" % (linked, len(nums), len(problems)))


if __name__ == "__main__":
    main()
